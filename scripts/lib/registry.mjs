// Regenerates src/videos/registry.ts from every src/videos/<id>/edit.json.
// If src/videos/<id>/Video.tsx exists (exporting `Video: React.FC<{ edit: Edit }>`), that custom
// component is registered for the composition instead of the plain AutoReel rough cut.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './media.mjs';

export function writeRegistry() {
  const videosDir = path.join(ROOT, 'src', 'videos');
  const ids = fs
    .readdirSync(videosDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(videosDir, d.name, 'edit.json')))
    .map((d) => d.name)
    .sort();
  const lines = [
    '// AUTO-GENERATED by scripts/lib/registry.mjs (npm run auto-edit / npm run registry). Do not edit by hand.',
    'import type React from "react";',
    'import type { Edit } from "../shared/AutoReel";',
  ];
  const entries = [];
  ids.forEach((id, i) => {
    lines.push(`import e${i} from "./${id}/edit.json";`);
    if (fs.existsSync(path.join(videosDir, id, 'Video.tsx'))) {
      lines.push(`import { Video as V${i} } from "./${id}/Video";`);
      entries.push(`{ edit: e${i} as Edit, component: V${i} }`);
    } else {
      entries.push(`{ edit: e${i} as Edit }`);
    }
  });
  lines.push('', 'export type VideoEntry = { edit: Edit; component?: React.FC<{ edit: Edit }> };', '', `export const VIDEOS: VideoEntry[] = [${entries.join(', ')}];`, '');
  fs.writeFileSync(path.join(videosDir, 'registry.ts'), lines.join('\n'));
  return ids;
}
